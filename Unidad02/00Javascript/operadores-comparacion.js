// ==
console.log(5 == "5"); // true

// ===
console.log(5 === "5"); // false

// !=
console.log(5 != "6"); // true

// !==
console.log(5 !== "5"); // true

// <
console.log(3 < 5); // true

// >
console.log(10 > 7); // true

// &&
let edad = 20;
let tieneEntrada = true;

console.log(edad >= 18 && tieneEntrada);
// true

// ||
let esAdmin = false;
let esProfesor = true;

console.log(esAdmin || esProfesor);
// true

// !
let llueve = false;

console.log(!llueve);
// true